    "### Step 4: 70% Train / 20% Validation / 10% Test Split & YOLO Export\n",
    "\n",
    "#### Understanding the 70-20-10 Split:\n",
    "* **Training Set (70%)**: The model directly learns weights and features from these images.\n",
    "* **Validation Set (20%)**: Evaluated at the end of every epoch to track learning, prevent overfitting, and save the best checkpoint (`best.pt`).\n",
    "* **Testing Set (10%)**: Kept completely untouched during training; used only for the final unbiased performance assessment in your report.\n",
    "\n",
    "#### Mathematical Splitting:\n",
    "Given $N$ total unique mammograms:\n",
    "* `train_cutoff = int(0.70 * N)` (First 70%)\n",
    "* `val_cutoff = int(0.90 * N)` (Next 20%, between index `train_cutoff` and `val_cutoff`)\n",
    "* `test = all_images[val_cutoff:]` (Remaining 10%)\n",
    "\n",
    "#### Normalizing Bounding Boxes to YOLO Format:\n",
    "$$\\text{YOLO format: } [\\text{class\\_id}, x_{\\text{center}}, y_{\\text{center}}, \\text{width}, \\text{height}]$$\n",
    "* $x_{\\text{center}} = \\frac{x_{\\min} + x_{\\max}}{2 \\times W}$\n",
    "* $y_{\\text{center}} = \\frac{y_{\\min} + y_{\\max}}{2 \\times H}$\n",
    "* $\\text{width} = \\frac{x_{\\max} - x_{\\min}}{W}$\n",
    "* $\\text{height} = \\frac{y_{\\max} - y_{\\min}}{H}$\n",
    "\n",
    "*(All values are normalized between 0.0 and 1.0, preserving relative box scale even when resizing to 640x640)*."
