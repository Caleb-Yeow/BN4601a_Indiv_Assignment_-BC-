    "                xmax = int((xc + bw / 2.0) * w)\n",
    "                ymax = int((yc + bh / 2.0) * h)\n",
    "                \n",
    "                color = class_colors.get(cls_id, (255, 255, 0))\n",
    "                draw.rectangle([xmin, ymin, xmax, ymax], outline=color, width=4)\n",
