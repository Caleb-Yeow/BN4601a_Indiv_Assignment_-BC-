    "def inspect_yolo_labels(num_images=4):\n",
    "    \"\"\"Plots sample images with their ground-truth bounding boxes drawn.\"\"\"\n",
    "    train_imgs = sorted(list((OUTPUT_DIR / 'images' / 'train').glob('*.jpg')))\n",
