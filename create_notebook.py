    "def process_and_save_split(split_name, image_paths, cases_map, target_size=(640, 640)):\n",
    "    \"\"\"\n",
    "    Processes mammograms for a split: computes bounding boxes from masks,\n",
    "    resizes images to target_size, and saves image and YOLO text files.\n",
    "    \"\"\"\n",
    "    saved_images = 0\n",
    "    total_boxes = 0\n",
    "    \n",
    "    for idx, img_path in enumerate(image_paths):\n",
    "        try:\n",
    "            # Open the full mammogram\n",
    "            full_img = Image.open(img_path).convert('RGB')\n",
    "            orig_w, orig_h = full_img.size\n",
    "            \n",
    "            base_name = f'{split_name}_{idx:04d}'\n",
    "            annotations = []\n",
    "            \n",
    "            # Compute bounding box from each lesion mask\n",
    "            for lesion in cases_map[img_path]:\n",
    "                mask_path = lesion['roi_path']\n",
    "                cls_id = lesion['class_id']\n",
    "                \n",
    "                mask_arr = np.array(Image.open(mask_path).convert('L'))\n",
    "                y_indices, x_indices = np.where(mask_arr > 0)\n",
    "                \n",
    "                # If mask has no white pixels, skip\n",
    "                if len(x_indices) == 0 or len(y_indices) == 0:\n",
    "                    continue\n",
    "                    \n",
    "                xmin, xmax = int(np.min(x_indices)), int(np.max(x_indices))\n",
    "                ymin, ymax = int(np.min(y_indices)), int(np.max(y_indices))\n",
    "                \n",
    "                # Convert to normalized YOLO coordinates [0, 1]\n",
    "                xc = ((xmin + xmax) / 2.0) / orig_w\n",
    "                yc = ((ymin + ymax) / 2.0) / orig_h\n",
    "                bw = (xmax - xmin) / float(orig_w)\n",
    "                bh = (ymax - ymin) / float(orig_h)\n",
    "                \n",
    "                # Bound coordinates safely between 0.0 and 1.0\n",
    "                xc = max(0.0, min(1.0, xc))\n",
    "                yc = max(0.0, min(1.0, yc))\n",
    "                bw = max(0.001, min(1.0, bw))\n",
    "                bh = max(0.001, min(1.0, bh))\n",
    "                \n",
    "                annotations.append(f'{cls_id} {xc:.6f} {yc:.6f} {bw:.6f} {bh:.6f}')\n",
    "                total_boxes += 1\n",
    "                \n",
    "            # Only save if at least one valid bounding box exists\n",
    "            if len(annotations) > 0:\n",
    "                # Resize image to target_size for fast processing & lightweight transfer\n",
    "                resized_img = full_img.resize(target_size, Image.Resampling.BILINEAR)\n",
    "                save_img_file = OUTPUT_DIR / 'images' / split_name / f'{base_name}.jpg'\n",
    "                resized_img.save(save_img_file, quality=95)\n",
    "                \n",
    "                # Write YOLO text label file\n",
    "                save_txt_file = OUTPUT_DIR / 'labels' / split_name / f'{base_name}.txt'\n",
    "                with open(save_txt_file, 'w') as f:\n",
    "                    f.write('\\n'.join(annotations) + '\\n')\n",
    "                    \n",
    "                saved_images += 1\n",
    "                \n",
    "        except Exception as e:\n",
    "            print(f'Error processing {img_path}: {e}')\n",
    "            \n",
    "    print(f'[{split_name.upper():5s}] Created {saved_images:4d} images with {total_boxes:4d} lesion bounding boxes.')\n",
    "\n",
    "# Process all splits\n",
    "for split_name in ['train', 'val', 'test']:\n",
    "    process_and_save_split(split_name, split_dict[split_name], all_cases_map, TARGET_SIZE)"
